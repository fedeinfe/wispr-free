/// A macOS modifier keycode and the event flags of its `flagsChanged` event: whether it went down.
/// `None` for keys without a held state (Caps Lock toggles) and non-modifiers.
pub fn mac_modifier_pressed(code: u16, flags: u64) -> Option<bool> {
    // NX_DEVICE*KEYMASK (IOLLEvent.h), which tell the sides apart, and kCGEventFlagMaskSecondaryFn.
    let mask = match code {
        0x36 => 0x10,
        0x37 => 0x08,
        0x38 => 0x02,
        0x3A => 0x20,
        0x3B => 0x01,
        0x3C => 0x04,
        0x3D => 0x40,
        0x3E => 0x2000,
        0x3F => 0x80_0000,
        _ => return None,
    };
    Some(flags & mask != 0)
}

/// A Windows virtual key as a low-level hook reports it (`VK_*`, WinUser.h).
pub fn windows_key(code: u32) -> Key {
    match code {
        0x08 => Key::Backspace,
        0x09 => Key::Tab,
        0x0D => Key::Enter,
        0x14 => Key::CapsLock,
        0x1B => Key::Esc,
        0x20 => Key::Space,
        0x21 => Key::PageUp,
        0x22 => Key::PageDown,
        0x23 => Key::End,
        0x24 => Key::Home,
        0x25 => Key::ArrowLeft,
        0x26 => Key::ArrowUp,
        0x27 => Key::ArrowRight,
        0x28 => Key::ArrowDown,
        0x2C => Key::PrintScreen,
        0x2D => Key::Insert,
        0x2E => Key::Delete,
        0x30..=0x39 | 0x41..=0x5A => Key::Char(char::from(code as u8)),
        0x5B => Key::Meta(Left),
        0x5C => Key::Meta(Right),
        0x70..=0x87 => Key::F((code - 0x6F) as u8),
        0xA0 => Key::Shift(Left),
        0xA1 => Key::Shift(Right),
        0xA2 => Key::Ctrl(Left),
        0xA3 => Key::Ctrl(Right),
        0xA4 => Key::Alt(Left),
        0xA5 => Key::Alt(Right),
        0xBA => Key::Char(';'),
        0xBB => Key::Char('='),
        0xBC => Key::Char(','),
        0xBD => Key::Char('-'),
        0xBE => Key::Char('.'),
        0xBF => Key::Char('/'),
        0xC0 => Key::Char('`'),
        0xDB => Key::Char('['),
        0xDC => Key::Char('\\'),
        0xDD => Key::Char(']'),
        0xDE => Key::Char('\''),
        other => Key::Other(other),
    }
}

/// A Linux evdev key or button code (`KEY_*`/`BTN_*`, linux/input-event-codes.h).
pub fn linux_key(code: u16) -> Key {
    const NUMBER_ROW: &[u8] = b"1234567890-=";
    const TOP_ROW: &[u8] = b"QWERTYUIOP[]";
    const HOME_ROW: &[u8] = b"ASDFGHJKL;'`";
    const BOTTOM_ROW: &[u8] = b"ZXCVBNM,./";
    let row = |row: &[u8], first: u16| Key::Char(char::from(row[usize::from(code - first)]));
    match code {
        1 => Key::Esc,
        2..=13 => row(NUMBER_ROW, 2),
        14 => Key::Backspace,
        15 => Key::Tab,
        16..=27 => row(TOP_ROW, 16),
        28 => Key::Enter,
        29 => Key::Ctrl(Left),
        30..=41 => row(HOME_ROW, 30),
        42 => Key::Shift(Left),
        43 => Key::Char('\\'),
        44..=53 => row(BOTTOM_ROW, 44),
        54 => Key::Shift(Right),
        56 => Key::Alt(Left),
        57 => Key::Space,
        58 => Key::CapsLock,
        59..=68 => Key::F((code - 58) as u8),
        87 => Key::F(11),
        88 => Key::F(12),
        97 => Key::Ctrl(Right),
        99 => Key::PrintScreen,
        100 => Key::Alt(Right),
        102 => Key::Home,
        103 => Key::ArrowUp,
        104 => Key::PageUp,
        105 => Key::ArrowLeft,
        106 => Key::ArrowRight,
        107 => Key::End,
        108 => Key::ArrowDown,
        109 => Key::PageDown,
        110 => Key::Insert,
        111 => Key::Delete,
        125 => Key::Meta(Left),
        126 => Key::Meta(Right),
        183..=194 => Key::F((code - 170) as u8),
        0x112 => Key::Mouse(MouseButton::Middle),
        0x113 => Key::Mouse(MouseButton::Back),
        0x114 => Key::Mouse(MouseButton::Forward),
        other => Key::Other(u32::from(other)),
    }
}
