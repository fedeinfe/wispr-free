// swift-tools-version: 6.2
import PackageDescription

// What `libwf_shell.a` needs at link time. `cargo xtask bridge` fails if rustc asks for one that
// isn't here (`--print native-static-libs`).
let frameworks = [
    "AVFoundation", "AppKit", "ApplicationServices", "AudioToolbox", "Carbon", "CloudKit",
    "CoreAudio", "CoreData", "CoreFoundation", "CoreGraphics", "CoreImage", "CoreMedia",
    "CoreServices", "CoreText", "CoreVideo", "Foundation", "IOKit", "Metal", "QuartzCore",
    "ScreenCaptureKit", "UniformTypeIdentifiers",
]
let libraries = ["iconv"]

let package = Package(
    name: "WisprFree",
    platforms: [.macOS(.v26)],
    targets: [
        .binaryTarget(name: "WfBridge", path: "WfBridge.xcframework"),
        // Generated by `cargo xtask bridge`. No defaultIsolation here: the build fails with it.
        .target(
            name: "WfCore",
            dependencies: ["WfBridge"],
            swiftSettings: [.swiftLanguageMode(.v6)],
            linkerSettings: frameworks.map { .linkedFramework($0) }
                + libraries.map { .linkedLibrary($0) }
        ),
        .executableTarget(
            name: "WisprFree",
            dependencies: ["WfCore"],
            swiftSettings: [.swiftLanguageMode(.v6), .defaultIsolation(MainActor.self)]
        ),
        .testTarget(
            name: "WisprFreeTests",
            dependencies: ["WisprFree", "WfCore"],
            swiftSettings: [.swiftLanguageMode(.v6)]
        ),
    ]
)
